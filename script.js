  function pickStudent() {
    const input = $("studentNames");
    if (!input) return;

    const names = input.value
      .split(/[,;\n]+/)
      .map(name => name.trim())
      .filter(Boolean);

    const result = $("studentResult");

    if (!names.length) {
      result.textContent =
        "Алдымен студенттердің есімдерін енгіз.";
      return;
    }

    if (!studentPool.length) {
      studentPool = [...new Set(names)];
    }

    const randomIndex = Math.floor(
      Math.random() * studentPool.length
    );

    const chosen = studentPool.splice(
      randomIndex,
      1
    )[0];

    result.textContent =
      "Таңдалған студент: " + chosen;
  }

