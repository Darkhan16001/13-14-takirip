  function toggleScore(button) {
    const team = Number(button.dataset.team);
    const key = button.dataset.key;
    const points = Number(button.dataset.points);

    if (!awarded[team]) return;

    if (awarded[team][key]) {
      delete awarded[team][key];
    } else {
      awarded[team][key] = points;
    }

    saveScores();
    updateScoreboard();

    document.querySelectorAll("[data-points]")
      .forEach(item => {
        const t = Number(item.dataset.team);
        const k = item.dataset.key;
        const active = Boolean(awarded[t][k]);

        item.classList.toggle(
          "awarded",
          active
        );

        item.textContent = active
          ? "✓ Ұпай берілді"
          : "+" + item.dataset.points + " ұпай";
      });
  }

